/**
 * 按项目标题匹配章节, 返回 { key, points } 或 null
 * points: [[no, 考点名, 总结], ...]
 */
export function findMayuanChapter(projectTitle) {
    if (!projectTitle) return null;
    if (projectTitle.includes('导论')) return MAYUAN_SUMMARIES.daolun;
    for (const key of ['ch1', 'ch2', 'ch3']) {
        const ch = MAYUAN_SUMMARIES[key];
        if (projectTitle.includes(ch.title.replace(/^第 \d 章 /, ''))) return ch;
    }
    return null;
}
